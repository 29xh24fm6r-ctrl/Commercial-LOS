#!/usr/bin/env node
// @ts-check
/**
 * Phase 190A -- Power Platform generated-artifact build recovery preflight.
 *
 * THE PROBLEM
 * -----------
 * `code-app/.power/` is gitignored (see the repo-root .gitignore rule
 * `code-app/.power/`). The generated Power Platform manifest
 *
 *     .power/schemas/appschemas/dataSourcesInfo.ts
 *
 * is therefore a LOCAL, never-committed artifact. A fresh clone does not
 * have it, so `tsc -b` fails with TS2307 across every generated service and
 * the two runtime readers that import it:
 *
 *     ../../.power/schemas/appschemas/dataSourcesInfo        (src/deals/*)
 *     ../../../.power/schemas/appschemas/dataSourcesInfo     (src/generated/services/*)
 *
 * THE FIX (offline, no Dataverse, no network, no secrets)
 * -------------------------------------------------------
 * This preflight makes a fresh clone buildable by writing a BUILD-ONLY
 * fallback manifest derived ENTIRELY from the tracked `power.config.json`
 * native (Dataverse) data sources. The fallback:
 *   - contains ONLY native entity-set names + `<logical>id` primary keys,
 *     which already appear verbatim across the committed generated services;
 *   - writes NO connection ids, environment urls, tenant ids, tokens,
 *     secrets, or connector `apis` -- exactly the same minimal native entry
 *     shape the Phase 170I sync script uses;
 *   - is clearly self-identified as a build-only fallback;
 *   - is GUID-free, offline, and idempotent.
 *
 * It NEVER overwrites an existing manifest. When a developer has pulled the
 * real local artifact (via the documented `pac code` path), `--ensure` is a
 * no-op, so live/runtime behaviour is never changed by this script.
 *
 * It performs NO Dataverse read or write, NO schema mutation, and NO
 * solution import/export. It only ever creates a local, gitignored file.
 *
 * Modes:
 *   node scripts/phase190A-power-artifact-preflight.mjs --ensure   # default; write fallback iff absent (exit 0)
 *   node scripts/phase190A-power-artifact-preflight.mjs --check    # verify only; exit 1 if the manifest is absent
 *
 * See docs/PHASE_190A_POWER_PLATFORM_GENERATED_ARTIFACT_BUILD_RECOVERY.md.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const POWER_CONFIG = 'power.config.json';
export const DATA_SOURCES_INFO = '.power/schemas/appschemas/dataSourcesInfo.ts';

/** The two relative import shapes that fail in a fresh clone. */
export const FAILING_IMPORT_SHAPES = Object.freeze([
  '../../.power/schemas/appschemas/dataSourcesInfo',
  '../../../.power/schemas/appschemas/dataSourcesInfo',
]);

/** The approved, no-secrets regeneration command operators should run. */
export const REGENERATION_COMMAND = 'pnpm power:schemas:ensure';

/**
 * Read the tracked native (Dataverse) data sources from power.config.json.
 * Returns `{ entitySetName, primaryKey }` pairs only -- no ids, no urls.
 * @param {string} configText raw power.config.json contents
 * @returns {{ entitySetName: string, primaryKey: string }[]}
 */
export function nativeDataSourcesFromConfig(configText) {
  const config = JSON.parse(configText);
  const cds = config?.databaseReferences?.['default.cds']?.dataSources ?? {};
  return Object.values(cds)
    .filter((s) => s && typeof s.entitySetName === 'string' && typeof s.logicalName === 'string')
    .map((s) => ({
      entitySetName: s.entitySetName,
      // Native Dataverse primary key = logical name + "id" (matches every
      // committed cr664_* / systemuser generated service).
      primaryKey: `${s.logicalName}id`,
    }))
    .sort((a, b) => a.entitySetName.localeCompare(b.entitySetName));
}

/**
 * Build the BUILD-ONLY fallback dataSourcesInfo.ts module text. Every entry
 * is a minimal native entry: empty tableId/version, `<logical>id` primary
 * key, dataSourceType "Dataverse", and an empty `apis` map. No secrets, no
 * urls, no ids, no connector definitions.
 * @param {{ entitySetName: string, primaryKey: string }[]} dataSources
 * @returns {string}
 */
export function buildDataSourcesInfoModule(dataSources) {
  const header =
    '/*\n' +
    ' * BUILD-ONLY FALLBACK -- generated by scripts/phase190A-power-artifact-preflight.mjs.\n' +
    ' *\n' +
    ' * This file is NOT the real Power Platform manifest. It is a local, gitignored,\n' +
    ' * type-only fallback that lets `tsc -b` resolve the generated-service imports in a\n' +
    ' * fresh clone that has no pulled `.power/` artifact. It carries ONLY native\n' +
    ' * Dataverse entity-set names + primary keys derived from the tracked\n' +
    ' * power.config.json. It contains no connection ids, environment urls, tenant\n' +
    ' * credentials, tokens, or connector apis. Do not commit it. A real deployment\n' +
    ' * must use the genuine artifact produced by the documented `pac code` pull.\n' +
    ' *\n' +
    ' * Regenerate: ' +
    REGENERATION_COMMAND +
    '\n' +
    ' */\n\n';

  const entries = dataSources
    .map(
      (s) =>
        `  "${s.entitySetName}": {\n` +
        `    "tableId": "",\n` +
        `    "version": "",\n` +
        `    "primaryKey": "${s.primaryKey}",\n` +
        `    "dataSourceType": "Dataverse",\n` +
        `    "apis": {}\n` +
        `  },\n`,
    )
    .join('');

  return header + 'export const dataSourcesInfo = {\n' + entries + '};\n';
}

function logCheckFailure() {
  console.error('phase190A preflight: the generated Power Platform manifest is ABSENT.');
  console.error(`  missing file : ${DATA_SOURCES_INFO}`);
  console.error('  failing imports that break `tsc -b` / `pnpm build`:');
  for (const shape of FAILING_IMPORT_SHAPES) console.error(`    - ${shape}`);
  console.error('  why: `.power/` is gitignored, so the manifest is a local artifact a fresh clone lacks.');
  console.error(`  fix: run \`${REGENERATION_COMMAND}\` to write a local build-only fallback,`);
  console.error('       or pull the real artifact via the documented `pac code` path.');
  console.error('  no-secrets warning: never commit `.power/`; the real manifest can carry tenant/connection metadata.');
  console.error('  runbook: docs/PHASE_190A_POWER_PLATFORM_GENERATED_ARTIFACT_BUILD_RECOVERY.md');
}

function runCli() {
  const mode = process.argv.includes('--check') ? 'check' : 'ensure';
  const present = existsSync(DATA_SOURCES_INFO);

  if (mode === 'check') {
    if (present) {
      console.log(`phase190A preflight: ${DATA_SOURCES_INFO} is present. OK.`);
      process.exit(0);
    }
    logCheckFailure();
    process.exit(1);
  }

  // ensure mode -- never overwrite a real/local pulled artifact.
  if (present) {
    console.log(`phase190A preflight: ${DATA_SOURCES_INFO} already present; leaving it untouched.`);
    process.exit(0);
  }

  if (!existsSync(POWER_CONFIG)) {
    console.error(`phase190A preflight: ${POWER_CONFIG} not found (run from code-app/). Cannot generate the fallback.`);
    process.exit(2);
  }

  const dataSources = nativeDataSourcesFromConfig(readFileSync(POWER_CONFIG, 'utf8'));
  if (dataSources.length === 0) {
    console.error(`phase190A preflight: no native data sources found in ${POWER_CONFIG}. Nothing to generate.`);
    process.exit(2);
  }

  mkdirSync(dirname(DATA_SOURCES_INFO), { recursive: true });
  writeFileSync(DATA_SOURCES_INFO, buildDataSourcesInfoModule(dataSources));
  console.log(
    `phase190A preflight: wrote a BUILD-ONLY fallback to ${DATA_SOURCES_INFO} ` +
      `(${dataSources.length} native entries; local + gitignored; not committed).`,
  );
  console.log('  no secrets were written; a real deployment must use the genuine `pac code` artifact.');
  process.exit(0);
}

// Only run the CLI when invoked directly (so the pure builders above stay importable from tests).
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  runCli();
}
